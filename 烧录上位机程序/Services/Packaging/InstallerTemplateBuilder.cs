using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using 烧录上位机程序.Models.Packaging;

namespace 烧录上位机程序.Services.Packaging;

public sealed class InstallerTemplateBuilder
{
    public const string InstalledIconName = "__dltools_app.ico";

    public string Build(PackagingOptions options, string stagingDirectory, string compilerOutputDirectory)
    {
        if (options.Mode != InstallerMode.Generated) throw new ArgumentException("只有通用模板模式可生成安装脚本。");
        RequireText(options.AppName, "应用名称");
        RequireText(options.AppVersion, "应用版本");
        if (options.AppId == Guid.Empty) throw new ArgumentException("请指定稳定的安装标识 AppId。");
        var executable = options.Project.MainExecutable;
        if (!string.Equals(PackagingFileSystem.NormalizeInstallerFileName(executable), executable, StringComparison.OrdinalIgnoreCase))
            throw new ArgumentException("项目入口必须是单一有效 EXE 文件名。");
        if (!File.Exists(Path.Combine(stagingDirectory, executable)))
            throw new FileNotFoundException("构建输出缺少项目入口 EXE。", executable);
        var filename = PackagingFileSystem.NormalizeInstallerFileName(options.InstallerFileName);
        var segment = PackagingFileSystem.SafeFileSegment(options.AppName);
        string RuntimeLiteral(string value) => value.Replace("{", "{{", StringComparison.Ordinal);
        var name = RuntimeLiteral(options.AppName);
        var pathSegment = RuntimeLiteral(segment);
        var exe = RuntimeLiteral(executable);
        var icon = exe;
        if (!string.IsNullOrWhiteSpace(options.IconPath))
        {
            PackagingFileSystem.EnsureNoLinks(options.IconPath);
            if (!File.Exists(options.IconPath)) throw new FileNotFoundException("未找到安装包图标。", options.IconPath);
            if (!File.Exists(Path.Combine(stagingDirectory, InstalledIconName)))
                throw new FileNotFoundException("安装包图标尚未收集至构建暂存目录。", InstalledIconName);
            icon = InstalledIconName;
        }
        var script = new StringBuilder();
        // Do not interpret metadata containing {#...} as executable ISPP expressions.
        // Only our own directives are emitted; user values never become preprocessor source.
        script.AppendLine("#pragma inlinestart \"DLTOOLS_INLINE_" + Guid.NewGuid().ToString("N") + "\"");
        script.AppendLine("; Generated by DL小工具. Stable AppId is stored in the project packaging profile.");
        script.AppendLine("[Setup]");
        script.AppendLine("AppId={{" + options.AppId.ToString("D") + "}");
        script.AppendLine("AppName=" + SetupValue(name));
        script.AppendLine("AppVersion=" + SetupValue(RuntimeLiteral(options.AppVersion)));
        script.AppendLine("VersionInfoVersion=" + PeVersion(options.AppVersion));
        script.AppendLine("DefaultDirName=" + SetupValue(@"{localappdata}\Programs\" + pathSegment));
        script.AppendLine("DefaultGroupName=" + SetupValue(pathSegment));
        script.AppendLine("PrivilegesRequired=lowest");
        script.AppendLine("DisableProgramGroupPage=yes");
        script.AppendLine("OutputDir=" + SetupValue(Path.GetFullPath(compilerOutputDirectory)));
        script.AppendLine("OutputBaseFilename=" + SetupValue(filename[..^4]));
        script.AppendLine("Compression=lzma2");
        script.AppendLine("SolidCompression=yes");
        script.AppendLine("WizardStyle=modern");
        script.AppendLine("UninstallDisplayIcon=" + SetupValue(@"{app}\" + icon));
        var x64 = options.Project.IsNetFramework
            ? options.Project.PlatformTarget.Equals("x64", StringComparison.OrdinalIgnoreCase)
            : options.RuntimeIdentifier == "win-x64";
        if (x64)
        {
            script.AppendLine("ArchitecturesAllowed=x64compatible");
            script.AppendLine("ArchitecturesInstallIn64BitMode=x64compatible");
        }
        if (!string.IsNullOrWhiteSpace(options.IconPath))
            script.AppendLine("SetupIconFile=" + SetupValue(Path.GetFullPath(options.IconPath)));
        var runtime = options.Project.IsNetFramework
            ? $"目标机须预先安装 .NET Framework {options.Project.FrameworkVersion} 或兼容版本。"
            : options.SelfContained ? "已包含 .NET 运行时。" : $"目标机须预先安装与 {options.Project.TargetFramework} 及 {options.RuntimeIdentifier} 匹配的 .NET Desktop Runtime。";
        RequireText(runtime, "运行时说明");
        script.AppendLine();
        script.AppendLine("[Languages]");
        script.AppendLine("Name: \"chinesesimplified\"; MessagesFile: " + Quote(options.Tools.ChineseLanguagePath));
        script.AppendLine();
        script.AppendLine("[Messages]");
        script.AppendLine("WelcomeLabel2=" + RuntimeLiteral(runtime) + " 安装过程中将允许选择安装位置。");
        script.AppendLine();
        if (options.CreateDesktopShortcut)
        {
            script.AppendLine("[Tasks]");
            script.AppendLine("Name: \"desktopicon\"; Description: \"创建桌面快捷方式\"; GroupDescription: \"附加选项:\"; Flags: unchecked");
            script.AppendLine();
        }
        script.AppendLine("[Files]");
        script.AppendLine("Source: " + Quote(Path.Combine(Path.GetFullPath(stagingDirectory), "*"))
            + "; DestDir: \"{app}\"; Flags: ignoreversion recursesubdirs createallsubdirs");
        script.AppendLine();
        script.AppendLine("[Icons]");
        script.AppendLine("Name: " + Quote(@"{group}\" + pathSegment) + "; Filename: " + Quote(@"{app}\" + exe)
            + "; IconFilename: " + Quote(@"{app}\" + icon));
        script.AppendLine("Name: " + Quote(@"{group}\卸载 " + pathSegment) + "; Filename: \"{uninstallexe}\"");
        if (options.CreateDesktopShortcut)
            script.AppendLine("Name: " + Quote(@"{autodesktop}\" + pathSegment) + "; Filename: " + Quote(@"{app}\" + exe)
                + "; IconFilename: " + Quote(@"{app}\" + icon) + "; Tasks: desktopicon");
        if (options.LaunchAfterInstall)
        {
            script.AppendLine();
            script.AppendLine("[Run]");
            script.AppendLine("Filename: " + Quote(@"{app}\" + exe) + "; Description: " + Quote("启动 " + name)
                + "; Flags: nowait postinstall skipifsilent");
        }
        return script.ToString();
    }

    private static string SetupValue(string text)
    {
        RequireText(text, "安装配置值");
        // [Setup] strips the outer quote pair but preserves interior quotes literally.
        // Parameter sections such as [Files]/[Icons] instead require doubled interior quotes.
        return "\"" + text + "\"";
    }

    private static string Quote(string text)
    {
        RequireText(text, "脚本文本");
        return "\"" + text.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";
    }

    private static void RequireText(string value, string label)
    {
        if (string.IsNullOrWhiteSpace(value) || value.Any(char.IsControl))
            throw new ArgumentException(label + "不能为空或包含换行、控制字符。");
    }

    private static string PeVersion(string value)
    {
        var match = Regex.Match(value, @"^\d+(?:\.\d+){0,3}");
        var components = match.Success ? match.Value.Split('.').ToList() : ["1", "0", "0"];
        if (components.Any(p => !ushort.TryParse(p, out _))) components = ["1", "0", "0"];
        while (components.Count < 4) components.Add("0");
        return string.Join('.', components);
    }
}
